/**
 * our-agent init <name> - Interactive scaffolding for new agents.
 */

import { resolve } from 'path';
import { existsSync, mkdirSync, writeFileSync } from 'fs';
import { createInterface } from 'readline/promises';

export async function initCommand(name, options) {
  const agentName = name || 'our-agent';
  const outDir = resolve(options.output || '.');
  const filePath = resolve(outDir, `${agentName}.conf`);

  if (existsSync(filePath) && !options.force) {
    console.error(`❌ ${filePath} already exists. Use --force to overwrite.`);
    process.exit(1);
  }

  const rl = createInterface({ input: process.stdin, output: process.stdout });

  console.log('\n  🛠️  Create a new our-agent\n');

  const answers = {
    name: await rl.question(`  Agent name [${agentName}]: `) || agentName,
    desc: await rl.question('  Description [A helpful AI assistant]: ') || 'A helpful AI assistant',
    prompt: await rl.question('  System prompt (one line, or leave blank for template): '),
    provider: await askChoice(rl, '  LLM provider', ['openai', 'anthropic', 'google', 'deepseek', 'ollama', 'openrouter'], 'openai'),
    temp: await rl.question('  Temperature [0.7]: ') || '0.7',
    maxTokens: await rl.question('  Max tokens [4096]: ') || '4096',
    tools: await askChoice(rl, '  Enable tools?', ['none', 'basic (search, file, time)', 'all'], 'basic'),
    icon: await rl.question('  Icon/emoji [🤖]: ') || '🤖',
    style: await askChoice(rl, '  Config style', ['brace {}', 'bracket []'], 'brace'),
  };

  rl.close();

  const temp = parseFloat(answers.temp);
  const maxTk = parseInt(answers.maxTokens);
  const useBrace = answers.style === 'brace {}';
  const toolList = answers.tools === 'none' ? [] 
    : answers.tools === 'all' ? ['web_search', 'read_file', 'write_file', 'list_files', 'execute_command', 'current_time']
    : ['web_search', 'read_file', 'current_time'];

  const sysPrompt = answers.prompt || `You are ${answers.name}, ${answers.desc}. Be helpful, concise, and friendly.`;

  let content = '';
  
  if (useBrace) {
    // Brace style
    content = `# ${answers.name} - ${answers.desc}
# Generated by our-agent init

agent {
    name = "${answers.name}";
    version = "1.0.0";
    desc = "${answers.desc}";

    prompt {
        system = """
${sysPrompt}
""";
        welcome = "Hello! I am ${answers.name}, how can I help you?";
    }

    settings {
        provider = "${answers.provider}";
        temperature = ${temp};
        max_tokens = ${maxTk};
        stream = true;
    }
`;

    if (toolList.length > 0) {
      content += `
    tools {
        allow = [${toolList.map(t => `"${t}"`).join(', ')}];
    }
`;
    }

    content += `
    ui {
        icon = "${answers.icon}";
        color = "#6366F1";
        theme = "modern";
    }
}
`;
  } else {
    // Bracket style
    content = `# ${answers.name} - ${answers.desc}
# Generated by our-agent init

[agent]
name = "${answers.name}"
version = "1.0.0"
desc = "${answers.desc}"

[prompt]
system = """
${sysPrompt}
"""
welcome = "Hello! I am ${answers.name}, how can I help you?"

[settings]
provider = "${answers.provider}"
temperature = ${temp}
max_tokens = ${maxTk}
stream = true
`;

    if (toolList.length > 0) {
      content += `
[tools]
allow = [${toolList.map(t => `"${t}"`).join(', ')}]
`;
    }

    content += `
[ui]
icon = "${answers.icon}"
color = "#6366F1"
theme = "modern"
`;
  }

  if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true });
  writeFileSync(filePath, content);

  console.log(`\n  ✅ Created: ${filePath}`);
  console.log(`  📋 ${answers.name} (${answers.provider})`);
  console.log(`  🔧 ${toolList.length > 0 ? toolList.length + ' tools enabled' : 'No tools'}`);
  console.log(`\n  Run it:\n    our-agent run "${filePath}"\n`);
}

async function askChoice(rl, question, choices, defaultChoice) {
  const labels = choices.map((c, i) => `${i + 1}) ${c}`).join('  ');
  const answer = await rl.question(`  ${question} [${defaultChoice}] (${labels}): `);
  const idx = parseInt(answer);
  if (idx >= 1 && idx <= choices.length) return choices[idx - 1];
  return answer || defaultChoice;
}
